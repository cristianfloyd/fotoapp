def publicar_foto(ruta, red):
  """Abre una ruta local (incluido Drive montado) o una URL directa de imagen.

  Devuelve un lienzo RGB del tamaño exacto de la red. Centra la fotografía,
  conserva sus proporciones y completa el espacio sobrante con gris medio
  RGB (128, 128, 128), sin recortar ni deformar. Puede ampliar imágenes pequeñas,
  pero eso no recupera detalle. No muestra ni guarda el resultado.

  En info registra tamano_original, tamano_contenido y area_contenido.
  El área usa (izquierda, arriba, derecha, abajo), con derecha y abajo excluidos,
  como Image.crop. Estos datos se mantienen en memoria; guardar y reabrir la
  imagen no garantiza conservarlos. Permiten distinguir foto y márgenes sin
  intentar reconocer el fondo por su color.

  Las redes se aceptan por nombre, sin distinguir mayúsculas, o por número
  del menú. Twitter también acepta el nombre X.
  Los enlaces a páginas de Drive no son URLs directas de imagen.
  """
  if not isinstance(ruta, str) or not ruta.strip():
    raise ValueError('Ingrese una ruta o URL de imagen válida')
  if not isinstance(red, str):
    raise ValueError('Ingrese el nombre o número de una red social')
  red = red.strip().upper()

  if red in ['YOUTUBE', '1']:
    ancho = 3840
    alto = 2160
  elif red in ['INSTAGRAM', '2']:
    ancho = 1080
    alto = 1080
  elif red in ['TWITTER', 'X', '3']:
    ancho = 1200
    alto = 675
  elif red in ['FACEBOOK', '4']:
    ancho = 1080
    alto = 1080
  elif red in ['TIKTOK', '5']:
    ancho = 1080
    alto = 1920
  elif red in ['PINTEREST', '6']:
    ancho = 1000
    alto = 1500
  elif red in ['LINKEDIN', '7']:
    ancho = 1200
    alto = 627
  elif red in ['THREADS', '8']:
    ancho = 1080
    alto = 1080
  elif red in ['SNAPCHAT', '9']:
    ancho = 1080
    alto = 1920
  else:
    raise ValueError(f'No se puede subir la imagen a {red}')

  if ruta.lower().startswith(('https://', 'http://')):
    respuesta = requests.get(ruta, timeout=15)
    respuesta.raise_for_status()
    origen = BytesIO(respuesta.content)
  else:
    origen = ruta

  with Image.open(origen) as imagen_original:
    imagen = ImageOps.exif_transpose(imagen_original).convert('RGB')

  escala = min(ancho / imagen.width, alto / imagen.height)
  nuevo_ancho = max(1, round(imagen.width * escala))
  nuevo_alto = max(1, round(imagen.height * escala))
  imagen_escalada = imagen.resize((nuevo_ancho, nuevo_alto), Image.Resampling.LANCZOS)
  izquierda = (ancho - nuevo_ancho) // 2
  arriba = (alto - nuevo_alto) // 2
  lienzo = Image.new('RGB', (ancho, alto), (128, 128, 128))
  lienzo.paste(imagen_escalada, (izquierda, arriba))
  lienzo.info['tamano_original'] = imagen.size
  lienzo.info['tamano_contenido'] = imagen_escalada.size
  lienzo.info['area_contenido'] = (izquierda, arriba,
                                  izquierda + nuevo_ancho, arriba + nuevo_alto)
  return lienzo

def _extraer_contenido(imagen):
  """Separa la foto usando sus coordenadas, nunca el color de los márgenes.

  Una imagen sin metadatos se considera una foto completa sin márgenes.
  Para conservar esta separación, use directamente la adaptación devuelta
  por publicar_foto; guardar y reabrir un archivo puede perder los metadatos.
  """
  if not isinstance(imagen, Image.Image):
    raise ValueError('Primero debe cargar una imagen válida de Pillow')
  area = imagen.info.get('area_contenido', (0, 0, imagen.width, imagen.height))
  if not isinstance(area, (tuple, list)) or len(area) != 4:
    raise ValueError('El área de contenido debe contener cuatro coordenadas')
  if not all(type(coordenada) is int for coordenada in area):
    raise ValueError('Las coordenadas del contenido deben ser números enteros')
  izquierda, arriba, derecha, abajo = area
  if not (0 <= izquierda < derecha <= imagen.width and 0 <= arriba < abajo <= imagen.height):
    raise ValueError('El área de contenido debe estar dentro de la imagen')
  area = tuple(area)
  return imagen.crop(area), area


def _recomponer_contenido(imagen, contenido, area):
  """Recompone la foto procesada sin aplicar operaciones sobre los márgenes."""
  resultado = imagen.convert(contenido.mode)
  resultado.paste(contenido, area[:2])
  resultado.info = imagen.info.copy()
  resultado.info['area_contenido'] = area
  return resultado


def ecualizador(imagen, archivo_salida='comparacion_ecualizada.png'):
  """Ecualiza solo la luminosidad Y de la fotografía y devuelve una imagen RGB.

  Conserva Cb y Cr antes de volver a RGB; la conversión y la saturación pueden
  introducir pequeñas variaciones cromáticas. No reconstruye detalle perdido.
  Los márgenes no participan en la ecualización ni en los histogramas.
  Muestra y guarda el original, el resultado y sus histogramas de luminosidad.
  No modifica la entrada y conserva sus metadatos de contenido. Use nombres de
  salida diferentes para conservar las pruebas oscura y sobreexpuesta;
  repetir el mismo nombre reemplaza la figura anterior.
  """
  contenido, area = _extraer_contenido(imagen)
  y, cb, cr = contenido.convert('YCbCr').split()
  luminosidad = np.array(y)
  y_ecualizada = Image.fromarray(cv2.equalizeHist(luminosidad))
  contenido_ecualizado = Image.merge('YCbCr', (y_ecualizada, cb, cr)).convert('RGB')
  resultado = _recomponer_contenido(imagen, contenido_ecualizado, area)
  luminosidad_resultado = np.array(contenido_ecualizado.convert('YCbCr'))[:, :, 0]

  figura, ejes = plt.subplots(2, 2, figsize=(12, 8))
  try:
    ejes[0, 0].imshow(imagen, cmap='gray', vmin=0, vmax=255)
    ejes[0, 0].set_title('Imagen original')
    ejes[0, 0].axis('off')

    ejes[0, 1].imshow(resultado)
    ejes[0, 1].set_title('Imagen ecualizada - luminosidad')
    ejes[0, 1].axis('off')

    for eje, valores, titulo in (
        (ejes[1, 0], luminosidad, 'Luminosidad original (sin márgenes)'),
        (ejes[1, 1], luminosidad_resultado, 'Luminosidad resultante (sin márgenes)')):
      eje.hist(valores.ravel(), bins=np.arange(257), color='gray')
      eje.set_xlim(0, 256)
      eje.set_title(titulo)
      eje.set_xlabel('Intensidad de luminosidad (Y)')
      eje.set_ylabel('Cantidad de píxeles')

    figura.tight_layout()
    figura.savefig(archivo_salida, dpi=150, bbox_inches='tight')
    plt.show()
  finally:
    plt.close(figura)

  return resultado

def filtros(imagen, filtro, archivo_salida=None):
  """Aplica un filtro por nombre o número, guarda la comparación y la muestra.

  Devuelve una nueva imagen de Pillow sin modificar el original.
  Procesa solo el área de contenido y conserva los márgenes y sus metadatos.
  Los nombres no distinguen mayúsculas. Si no se indica archivo_salida, el nombre incluye
  el filtro, por ejemplo comparacion_edge_enhance.png. Repetir el mismo filtro
  sobre otra foto requiere una ruta distinta para conservar ambas figuras.
  """
  if not isinstance(imagen, Image.Image):
    raise ValueError('Primero debe cargar una imagen válida de Pillow')
  if not isinstance(filtro, str):
    raise ValueError('Ingrese el nombre o número de un filtro')

  filtros_disponibles = [
    ('Blur', ImageFilter.BLUR),
    ('Contour', ImageFilter.CONTOUR),
    ('Detail', ImageFilter.DETAIL),
    ('Edge Enhance', ImageFilter.EDGE_ENHANCE),
    ('Edge Enhance More', ImageFilter.EDGE_ENHANCE_MORE),
    ('Emboss', ImageFilter.EMBOSS),
    ('Find Edges', ImageFilter.FIND_EDGES),
    ('Sharpen', ImageFilter.SHARPEN),
    ('Smooth', ImageFilter.SMOOTH),
  ]
  seleccion = filtro.strip().lower()
  for numero, (nombre, filtro_pillow) in enumerate(filtros_disponibles, start=1):
    if seleccion in (nombre.lower(), str(numero)):
      break
  else:
    raise ValueError(f'No se puede aplicar el filtro {filtro}')

  contenido, area = _extraer_contenido(imagen)
  imagen_filtrada = _recomponer_contenido(imagen, contenido.filter(filtro_pillow), area)
  if archivo_salida is None:
    archivo_salida = f"comparacion_{nombre.lower().replace(' ', '_')}.png"

  figura, ejes = plt.subplots(1, 2, figsize=(12, 5))
  try:
    ejes[0].imshow(imagen, cmap='gray', vmin=0, vmax=255)
    ejes[0].set_title('Imagen original')
    ejes[0].axis('off')

    ejes[1].imshow(imagen_filtrada, cmap='gray', vmin=0, vmax=255)
    ejes[1].set_title(nombre)
    ejes[1].axis('off')

    figura.tight_layout()
    figura.savefig(archivo_salida, dpi=150, bbox_inches='tight')
    plt.show()
  finally:
    plt.close(figura)

  return imagen_filtrada

def boceto(image, metodo, invertir, umbral, kernel, umbral1=50, umbral2=150,
           archivo_salida=None):
  """Devuelve un boceto uint8 y guarda la comparación con el original.

  Acepta Canny, Sobel, Laplaciano o Umbral, también por número del menú.
  Canny usa umbral1 y umbral2 (0 <= umbral1 < umbral2 <= 255) y un núcleo
  de 3, 5 o 7. Las otras técnicas usan umbral; Umbral no usa un núcleo.
  invertir intercambia negro y blanco. El archivo predeterminado incluye
  la técnica y la inversión; use otra ruta para conservar distintas pruebas
  de parámetros o fotografías. No modifica la imagen recibida.
  El contenido es binario (0 o 255); los márgenes conservan su gris original
  incluso al invertir. Los gradientes y la normalización excluyen los márgenes.
  """
  if not isinstance(image, Image.Image):
    raise ValueError('Primero debe cargar una imagen válida de Pillow')
  if not isinstance(metodo, str):
    raise ValueError('Ingrese el nombre o número de una técnica')
  if not isinstance(invertir, bool):
    raise ValueError('La opción invertir debe ser True o False')

  metodo = metodo.strip().capitalize()
  nombres_metodos = {'1': 'Canny', '2': 'Sobel', '3': 'Laplaciano', '4': 'Umbral'}
  metodo = nombres_metodos.get(metodo, metodo)
  if metodo not in nombres_metodos.values():
    raise ValueError(f'El método {metodo} no es válido')

  if metodo == 'Canny':
    if not isinstance(kernel, int) or kernel not in (3, 5, 7):
      raise ValueError('Canny requiere un núcleo de tamaño 3, 5 o 7')
    if not isinstance(umbral1, int) or not isinstance(umbral2, int):
      raise ValueError('Los umbrales de Canny deben ser números enteros')
    if not 0 <= umbral1 < umbral2 <= 255:
      raise ValueError('Canny requiere 0 <= umbral1 < umbral2 <= 255')
  else:
    if not isinstance(umbral, int) or not 0 <= umbral <= 255:
      raise ValueError('El umbral debe ser un número entero entre 0 y 255')
    if metodo != 'Umbral':
      if not isinstance(kernel, int) or kernel not in (1, 3, 5, 7, 9):
        raise ValueError('El núcleo debe tener tamaño 1, 3, 5, 7 o 9')

  contenido, area = _extraer_contenido(image)
  imagen = np.array(contenido.convert('RGB'))
  gris = cv2.cvtColor(imagen, cv2.COLOR_RGB2GRAY)
  gris = cv2.normalize(gris, None, 0, 255, cv2.NORM_MINMAX).astype(np.uint8)

  if metodo == 'Canny':
    bordes = cv2.Canny(gris, umbral1, umbral2, apertureSize=kernel)
  elif metodo == 'Sobel':
    gx = cv2.Sobel(gris, cv2.CV_64F, 1, 0, ksize=kernel)
    gy = cv2.Sobel(gris, cv2.CV_64F, 0, 1, ksize=kernel)
    magnitud = np.sqrt(gx**2 + gy**2)
    _, bordes = cv2.threshold(magnitud, umbral, 255, cv2.THRESH_BINARY)
  elif metodo == 'Laplaciano':
    laplaciano = cv2.Laplacian(gris, cv2.CV_64F, ksize=kernel)
    laplaciano = np.abs(laplaciano)
    laplaciano = cv2.normalize(laplaciano, None, 0, 255, cv2.NORM_MINMAX).astype(np.uint8)
    _, bordes = cv2.threshold(laplaciano, umbral, 255, cv2.THRESH_BINARY)
  else:
    _, bordes = cv2.threshold(gris, umbral, 255, cv2.THRESH_BINARY)

  bordes = bordes.astype(np.uint8)
  if invertir:
    imagen_binaria = cv2.bitwise_not(bordes)
  else:
    imagen_binaria = bordes.copy()

  imagen_binaria = np.array(_recomponer_contenido(image, Image.fromarray(imagen_binaria), area))

  if archivo_salida is None:
    sufijo = '_invertido' if invertir else ''
    archivo_salida = f'comparacion_boceto_{metodo.lower()}{sufijo}.png'

  figura, ejes = plt.subplots(1, 2, figsize=(12, 5))
  try:
    ejes[0].imshow(image, cmap='gray', vmin=0, vmax=255)
    ejes[0].set_title('Imagen original')
    ejes[0].axis('off')

    ejes[1].imshow(imagen_binaria, cmap='gray', vmin=0, vmax=255)
    ejes[1].set_title(f'Boceto - {metodo}')
    ejes[1].axis('off')

    figura.tight_layout()
    figura.savefig(archivo_salida, dpi=150, bbox_inches='tight')
    plt.show()
  finally:
    plt.close(figura)

  return imagen_binaria

def mostrar_y_guardar_imagen(imagen_original, imagen_modificada, titulo_modificada, cmap):
  plt.figure(figsize=(12, 5)) #Configura el tamaño del plt

  #En el subplot de la izquierda se muestra la imagen original
  plt.subplot(1, 2, 1)
  plt.title("Imagen original")
  plt.axis("off")
  plt.imshow(imagen_original)

  #En el subplot de la derecha se muestra la nueva imagen
  plt.subplot(1, 2, 2)
  plt.title(f"{titulo_modificada}")
  plt.axis("off")
  if cmap == ' ':
    plt.imshow(imagen_modificada)
  else:
    plt.imshow(imagen_modificada, cmap=cmap)

  #Compara ambas imágenes
  plt.tight_layout()
  plt.show()
  #Limpia la pantalla lugo de 10 segundos
  time.sleep(10)
  clear_output(wait=True)
  #Pregunta si se desea guardar la nueva imagen
  opcion = input('¿Desea guardar la imagen? ')
  opcion = opcion.capitalize()
  if opcion == 'Sí':
    cv2.imwrite(f"{titulo_modificada}.jpg", imagen_modificada) #La guarda
  elif opcion == 'No':
    pass #No la guarda
  else:
    raise ValueError('Ingrese una opción válida')
